async function seedWhatsAppSyncLog(
  accountId: string,
  productIds: Map<string, string>
): Promise<void> {
  const rows: Row[] = [];
  for (const [code, id] of productIds) {
    const seed = PRODUCT_SEEDS.find((p) => p.code === code)!;
    let syncStatus: string;
    let lastSyncedAt: string | null = null;
    let syncError: string | null = null;

    if (code === 'RIM-HDD-15W40') {
      syncStatus = 'Synced';
      lastSyncedAt = hoursAgo(48);
    } else if (code === 'RIM-HDD-20W50') {
      syncStatus = 'Sync Error';
      syncError = 'Catalogue rejected: missing required attribute (GTIN).';
    } else if (seed.status === 'published') {
      syncStatus = 'Pending Review';
    } else {
      syncStatus = 'Draft';
    }

    rows.push({
      account_id: accountId,
      product_id: id,
      sync_status: syncStatus,
      last_synced_at: lastSyncedAt,
      sync_error: syncError,
    });
  }
  await insert('whatsapp_sync_log', rows);
}

