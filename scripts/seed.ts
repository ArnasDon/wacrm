async function findUserByEmail(email: string) {
  let page = 1;
  const perPage = 200;
  for (;;) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage });
    if (error) throw new Error(`listUsers failed: ${error.message}`);
    const match = data.users.find((u) => u.email === email);
    if (match) return match;
    if (data.users.length < perPage) return null;
    page += 1;
  }
}

async function getOrCreateDemoUser(): Promise<string> {
  const { data, error } = await admin.auth.admin.createUser({
    email: DEMO_EMAIL,
    password: DEMO_PASSWORD,
    email_confirm: true,
    user_metadata: { full_name: 'Rimula Demo Admin' },
  });
  if (!error && data.user) {
    console.log(`Created demo user ${DEMO_EMAIL} (${data.user.id})`);
    return data.user.id;
  }

  // Most likely cause of failure on a re-run: the user already
  // exists. Look it up instead of treating that as fatal.
  const existing = await findUserByEmail(DEMO_EMAIL);
  if (existing) {
    console.log(`Reusing existing demo user ${DEMO_EMAIL} (${existing.id})`);
    return existing.id;
  }

  throw new Error(
    `Could not create or find demo user ${DEMO_EMAIL}: ${error?.message ?? 'unknown error'}`
  );
}

async function getAccountId(userId: string): Promise<string> {
  const { data, error } = await admin
    .from('profiles')
    .select('account_id')
    .eq('user_id', userId)
    .single();
  if (error || !data) {
    throw new Error(
      `No profile/account found for demo user ${userId}. Was migration 017 (handle_new_user trigger) applied? (${error?.message ?? 'no rows'})`
    );
  }
  return data.account_id as string;
}

