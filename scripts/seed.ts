function loadEnvLocal(): void {
  const envPath = path.resolve(process.cwd(), '.env.local');
  if (!existsSync(envPath)) return;
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function requireEnv(name: string): string {
  const value = process.env[name];
  if (!value) {
    throw new Error(
      `Missing required env var ${name}. Set it in .env.local (see .env.local.example) before running the seed script.`
    );
  }
  return value;
}

function pick<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

function hoursAgo(n: number): string {
  return new Date(Date.now() - n * 3_600_000).toISOString();
}

async function insert(table: string, rows: Row[]): Promise<void> {
  if (rows.length === 0) return;
  const { error } = await admin.from(table).insert(rows);
  if (error) {
    throw new Error(`Failed to insert into "${table}": ${error.message}`);
  }
}

async function cleanup(accountId: string): Promise<void> {
  for (const table of CLEANUP_TABLES) {
    const { error } = await admin
      .from(table)
      .delete()
      .eq('account_id', accountId);
    if (error) {
      throw new Error(`Failed to clean up "${table}": ${error.message}`);
    }
  }
}

