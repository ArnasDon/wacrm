async function seedProducts(
  accountId: string,
  userId: string,
  categoryIds: Map<string, string>
): Promise<Map<string, string>> {
  const productIds = new Map(PRODUCT_SEEDS.map((p) => [p.code, randomUUID()]));

  await insert(
    'products',
    PRODUCT_SEEDS.map((p) => ({
      id: productIds.get(p.code),
      account_id: accountId,
      category_id: categoryIds.get(p.category) ?? null,
      product_code: p.code,
      product_name: p.name,
      description: p.description,
      short_description: p.shortDescription,
      long_description: p.longDescription,
      key_features: p.keyFeatures,
      benefits: p.benefits,
      vehicle_types: p.vehicleTypes,
      recommended_vehicles: p.recommendedVehicles,
      engine_types: p.engineTypes,
      packaging: p.packaging,
      status: p.status,
      created_by: userId,
    }))
  );
  return productIds;
}

