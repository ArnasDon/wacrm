/**
 * scripts/seed.ts — Rimula demo/dev seed data
 *
 * Populates the net-new Rimula tables added in migrations 040-051:
 * Products, Vehicles, verified compatibility, Campaigns, Content +
 * translations + voice notes, Customer Requests, Trials, Engagement
 * events, Product interactions, WhatsApp sync log (Phase 1), plus
 * Markets, Regions, and the full §19 Member volumes on `contacts`,
 * and BA fields on the demo profile (Phase 2). Per §19 of
 * docs/RIMULA_BUILD_SPEC.md.
 *
 * §19 reference volumes (seeded exactly):
 *
 *   | Segment      | Total | WhatsApp confirmed |
 *   |--------------|-------|---------------------|
 *   | Mechanics    |   202 |                 154 |
 *   | Truck Owners |   255 |                 187 |
 *   | Drivers      |   387 |                 278 |
 *   | Total        |   844 |                 619 |
 *
 * across 20 markets grouped into 5 regions.
 *
 * WHY PROGRAMMATIC, NOT A .sql FILE: everything below goes through
 * `@supabase/supabase-js` — the same client every other admin/service
 * path in this codebase uses (mirrors `src/lib/automations/admin-client.ts`).
 * No raw SQL is written or executed here, so there's no dialect to get
 * wrong; every statement the server ever sees is a plain Postgres
 * INSERT/DELETE generated by the client library.
 *
 * LOCAL / DEV ONLY. Uses the Supabase Admin API
 * (`auth.admin.createUser`) to provision a demo login — this requires
 * `SUPABASE_SERVICE_ROLE_KEY` and bypasses RLS entirely, so never run
 * this against a hosted/production project. The demo account is
 * looked up by email and reused across runs, so a fresh
 * `accounts`/`profiles` row is only created once.
 *
 * Idempotent / re-runnable: every Rimula-domain row belonging to the
 * demo account is deleted and reinserted fresh on every run (see
 * CLEANUP_TABLES below). Row ids are regenerated each run — nothing
 * in the spec requires them to be stable across seed runs, only that
 * the script is safe to run repeatedly.
 *
 * Usage:
 *   npm run db:seed
 */

